#!/bin/sh
# Runs after the nginx image's envsubst step (20-). nginx cannot branch on environment variables, so this script
#  * selects the auth snippets for AUTH_MODE, and
#  * renders the host layout:
#      AUTH_HOST  empty or = APP_HOST -> Authelia portal at https://APP_HOST/auth/   (single domain, the default)
#                 another hostname    -> its own server block (separate login host)
#      FILES_HOST empty or = APP_HOST -> signed downloads at https://APP_HOST/dl/     (single domain, the default)
#                 another hostname    -> its own server block; /dl/ on APP_HOST answers 404
# Output: $GATEWAY_OUT (default /tmp/gateway)/{auth-page,auth-api,app-locations,servers}.conf, all included by
# templates/gateway.conf.template. GATEWAY_SNIPPETS / GATEWAY_OUT exist so the script can be run outside the image.
# POSIX sh (busybox ash in the image): no bashisms.
set -eu
mode="${AUTH_MODE:-authelia}"
snip="${GATEWAY_SNIPPETS:-/etc/nginx/snippets}"
out="${GATEWAY_OUT:-/tmp/gateway}"
mkdir -p "$out"

die() { echo "gateway: $*" >&2; exit 1; }
lower() { printf '%s' "$1" | tr '[:upper:]' '[:lower:]'; }
# Whole-string check (a newline or any other character outside [a-z0-9.-] fails): the value is pasted into nginx config.
valid_host() {
  case "$1" in ""|*[!a-z0-9.-]*|.*|*.|-*|*-|*..*|*.-*|*-.*) return 1 ;; esac
  [ "${#1}" -le 253 ]
}

[ -n "${GATEWAY_SECRET:-}" ] || die "GATEWAY_SECRET must be set"

app=$(lower "${APP_HOST:-}")
auth=$(lower "${AUTH_HOST:-}")
files=$(lower "${FILES_HOST:-}")
[ -n "$app" ] || die "APP_HOST must be set"
valid_host "$app" || die "APP_HOST is not a valid hostname: '$app'"
[ -z "$auth" ] || valid_host "$auth" || die "AUTH_HOST is not a valid hostname: '$auth' (leave it empty for the single-domain layout)"
[ -z "$files" ] || valid_host "$files" || die "FILES_HOST is not a valid hostname: '$files' (leave it empty for the single-domain layout)"
[ "$auth" != "$app" ] || auth=""
[ "$files" != "$app" ] || files=""
if [ -n "$auth" ] && [ "$auth" = "$files" ]; then die "AUTH_HOST and FILES_HOST must be different hostnames"; fi

case "$mode" in
  authelia)
    cp "$snip/auth-authelia-page.conf" "$out/auth-page.conf"
    cp "$snip/auth-authelia-api.conf" "$out/auth-api.conf"
    ;;
  external)
    echo "gateway: AUTH_MODE=external - trusting Remote-* headers from the upstream proxy." >&2
    echo "gateway: The gateway must be reachable ONLY from your SSO proxy." >&2
    cp "$snip/auth-external.conf" "$out/auth-page.conf"
    cp "$snip/auth-external.conf" "$out/auth-api.conf"
    ;;
  *)
    die "AUTH_MODE must be 'authelia' or 'external' (got '$mode')"
    ;;
esac

# --- locations added to the APP_HOST server ----------------------------------------------------------------------
{
  echo "# Generated by 25-gateway-auth-mode.sh: AUTH_HOST=${auth:-<app host>} FILES_HOST=${files:-<app host>} AUTH_MODE=$mode"
  if [ -z "$auth" ] && [ "$mode" = authelia ]; then
    cat <<EOF
# Authelia portal under /auth/ (no login required to reach the login page). ^~ wins over every regex location; the
# exact /auth adds the slash without losing the query.
location = /auth {
  absolute_redirect off;
  return 301 /auth/\$is_args\$args;
}
location ^~ /auth/ {
  include $snip/authelia-portal.conf;
}
EOF
  fi
  if [ -z "$files" ]; then
    echo "include $snip/files-locations.conf;"
  else
    echo "# Downloads have their own host ($files): one canonical place for /dl/."
    echo "location ^~ /dl/ { return 404; }"
  fi
} > "$out/app-locations.conf"

# --- extra server blocks for separate hosts ---------------------------------------------------------------------
{
  echo "# Generated by 25-gateway-auth-mode.sh"
  if [ -n "$auth" ]; then sed "s/@HOST@/$auth/g" "$snip/server-auth.conf.in"; fi
  if [ -n "$files" ]; then sed "s/@HOST@/$files/g" "$snip/server-files.conf.in"; fi
} > "$out/servers.conf"

echo "gateway: app=$app login=${auth:-$app/auth/} downloads=${files:-$app/dl/} (AUTH_MODE=$mode)" >&2
