import { createHash } from 'node:crypto';
import { env } from './env';
import { raw } from './net';

export const sha256 = (b: Buffer): string => createHash('sha256').update(b).digest('hex');

export interface FixtureFile { path: string; size: number; sha256: string }
export interface FixtureTorrent { name: string; infohash: string; torrent: string; magnet: string; files: FixtureFile[] }
export interface Manifest { tracker: string; multi: FixtureTorrent; single: FixtureTorrent; slow: FixtureTorrent }

let manifest: Manifest | null = null;
/** Seeder fixture: torrents, magnets and sha256 sums (served by the TLS front from the shared fixtures volume). */
export async function getManifest(): Promise<Manifest> {
  if (manifest) return manifest;
  const r = await raw(`${env.fixturesURL}/manifest.json`);
  if (r.status !== 200) throw new Error(`fixtures manifest: HTTP ${r.status}`);
  manifest = JSON.parse(r.body.toString('utf8')) as Manifest;
  return manifest;
}
export async function fixtureFile(path: string): Promise<Buffer> {
  const r = await raw(`${env.fixturesURL}/${path}`);
  if (r.status !== 200) throw new Error(`fixture ${path}: HTTP ${r.status}`);
  return r.body;
}
/** Client-side WireGuard config generated by the wg1/wg2 server fixtures at test time. */
export const wgConfig = async (name: 'wg1' | 'wg2'): Promise<string> => (await fixtureFile(`wg/${name}.conf`)).toString('utf8');

/** A magnet nobody seeds: the download never starts, so the job stays active until cancelled. */
export function stalledMagnet(tag: string): string {
  const hash = createHash('sha1').update(`stalled-${tag}-${Date.now()}-${Math.random()}`).digest('hex');
  return `magnet:?xt=urn:btih:${hash}&dn=stalled-${tag}`;
}
export const hashOfMagnet = (m: string): string => /btih:([0-9a-f]{40})/i.exec(m)![1]!.toLowerCase();

// ---- control service (docker access for the suite) ---------------------------------------------------------
async function ctl(path: string, init: { method?: string; body?: unknown } = {}): Promise<any> {
  const r = await raw(`${env.ctlURL}${path}`, {
    method: init.method ?? 'GET',
    headers: { authorization: `Bearer ${env.ctlToken}`, ...(init.body ? { 'content-type': 'application/json' } : {}) },
    body: init.body ? JSON.stringify(init.body) : undefined,
  });
  const json = JSON.parse(r.body.toString('utf8') || '{}');
  if (r.status !== 200) throw new Error(`ctl ${path}: HTTP ${r.status} ${JSON.stringify(json)}`);
  return json;
}
export const restartServices = (...services: string[]): Promise<void> => ctl('/restart', { method: 'POST', body: { services } });

export interface Probe { reachable: boolean; status: number; body: string; error: string }
/** curl executed inside the qbittorrent container (the VPN network namespace, uid 1000). */
export const probe = (url: string): Promise<Probe> => ctl(`/probe?url=${encodeURIComponent(url)}`);

export interface QbtTorrent { hash: string; name: string; state: string; progress: number; category: string }
/** The torrents qBittorrent currently holds (read from inside its own namespace; the WebUI is not exposed). */
export async function qbtTorrents(): Promise<QbtTorrent[]> {
  const p = await probe('http://127.0.0.1:8080/api/v2/torrents/info');
  if (!p.reachable || p.status !== 200) throw new Error(`qbt unreachable: ${p.error || p.status}`);
  return JSON.parse(p.body) as QbtTorrent[];
}
export async function qbtPreferences(): Promise<Record<string, any>> {
  const p = await probe('http://127.0.0.1:8080/api/v2/app/preferences');
  if (!p.reachable || p.status !== 200) throw new Error(`qbt unreachable: ${p.error || p.status}`);
  return JSON.parse(p.body);
}
