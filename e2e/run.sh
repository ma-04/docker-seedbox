#!/usr/bin/env bash
# Hermetic end-to-end run: build images, start the stack (deploy/compose.yaml + deploy/compose.e2e.yaml),
# run the Playwright suite inside the compose network, collect reports/logs into e2e/.out, tear everything down.
#
#   e2e/run.sh [options] [-- <playwright args>]
#     --keep        leave the stack running afterwards (for debugging, or for the dev-machine mode)
#     --publish     publish the TLS front on 127.0.0.1:$E2E_PUBLISH_PORT (default 18443) for `ssh -L`; implies nothing else
#     --no-build    reuse images from an earlier run
#     --no-tests    only start the stack (use with --keep)
#     --rmi         remove the images built by this script when tearing down
#     --search S    torrent search: on (default: $E2E_SEARCH or on; Jackett + the mock indexer) | off (search disabled)
#     --layout L    hosts layout (default: $E2E_LAYOUT or single):
#                     single       app, Authelia (/auth/) and downloads (/dl/) on app.seedbox.test
#                     split-files  app + Authelia on app.seedbox.test, downloads on files.seedbox.test
#                     multi        app., auth. and files.seedbox.test (the layout before single-domain support)
#   Examples:
#     e2e/run.sh                              # CI: everything, then tear down
#     e2e/run.sh -- tests/03-local-download.spec.ts
#     e2e/run.sh --layout multi -- tests/01-auth.spec.ts
#     e2e/run.sh --keep --publish --no-tests  # then, from a laptop: see e2e/README.md
set -uo pipefail
cd "$(dirname "$0")/.."
ROOT=$PWD
STATE=$ROOT/e2e/.state
OUT=$ROOT/e2e/.out
KEEP=0 PUBLISH=0 BUILD=1 TESTS=1 RMI=0
LAYOUT=${E2E_LAYOUT:-single}
SEARCH=${E2E_SEARCH:-on}
PW_ARGS=()
while [ $# -gt 0 ]; do
  case "$1" in
    --keep) KEEP=1 ;; --publish) PUBLISH=1 ;; --no-build) BUILD=0 ;; --no-tests) TESTS=0 ;; --rmi) RMI=1 ;;
    --layout) LAYOUT=${2:?--layout needs a value}; shift ;;
    --search) SEARCH=${2:?--search needs on or off}; shift ;;
    --) shift; PW_ARGS=("$@"); break ;;
    -h|--help) sed -n '2,22p' "$0"; exit 0 ;;
    *) echo "unknown option $1" >&2; exit 2 ;;
  esac
  shift
done
case "$LAYOUT" in
  single)      HOSTS=$'AUTH_HOST=\nFILES_HOST=\nCOOKIE_DOMAIN=' ;;
  split-files) HOSTS=$'AUTH_HOST=\nFILES_HOST=files.seedbox.test\nCOOKIE_DOMAIN=' ;;
  multi)       HOSTS=$'AUTH_HOST=auth.seedbox.test\nFILES_HOST=files.seedbox.test\nCOOKIE_DOMAIN=seedbox.test' ;;
  *) echo "unknown --layout $LAYOUT (single | split-files | multi)" >&2; exit 2 ;;
esac

case "$SEARCH" in
  on)  SEARCH_ENV=$'SEARCH_BACKEND=jackett\nFLARESOLVERR_ENABLED=' ;;
  off) SEARCH_ENV=$'SEARCH_BACKEND=\nFLARESOLVERR_ENABLED=' ;;
  *) echo "unknown --search $SEARCH (on | off)" >&2; exit 2 ;;
esac

export COMPOSE_PROJECT_NAME=${COMPOSE_PROJECT_NAME:-sbe2e}
# Never collide with (or overwrite) images of a real installation on the same Docker host.
export SEEDBOX_REGISTRY=sbe2e SEEDBOX_VERSION=e2e
export PW_VERSION; PW_VERSION=$(sed -n 's/.*"@playwright\/test": *"\([0-9.]*\)".*/\1/p' e2e/package.json | head -1)
export E2E_UID=${E2E_UID:-$(id -u)} E2E_GID=${E2E_GID:-$(id -g)}

mkdir -p "$STATE" "$OUT"
chmod 700 "$STATE"
rand() { head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; }
if [ -f "$STATE/e2e.env" ] && { ! grep -qx "E2E_LAYOUT=$LAYOUT" "$STATE/e2e.env" || ! grep -qx "E2E_SEARCH_MODE=$SEARCH" "$STATE/e2e.env"; }; then
  echo "e2e: e2e/.state/e2e.env belongs to another layout/search mode ($(sed -n 's/^E2E_\(LAYOUT\|SEARCH_MODE\)=//p' "$STATE/e2e.env" | tr '\n' ' ')); tear that stack down first" >&2
  exit 2
fi
if [ ! -f "$STATE/e2e.env" ]; then
  umask 077
  cat > "$STATE/e2e.env" <<ENV
# Generated by e2e/run.sh. Throw-away secrets for the hermetic stack; never commit.
E2E_LAYOUT=$LAYOUT
E2E_SEARCH_MODE=$SEARCH
$SEARCH_ENV
JACKETT_API_KEY=$(rand 16)
APP_HOST=app.seedbox.test
$HOSTS
PUBLIC_SCHEME=https
AUTH_MODE=authelia
AUTH_POLICY=one_factor
ADMIN_GROUP=admins
LAN_CIDRS=172.31.250.0/24
APP_SECRET=$(rand 32)
GATEWAY_SECRET=$(rand 32)
VPN_CONTROL_TOKEN=$(rand 24)
AUTHELIA_SESSION_SECRET=$(rand 32)
AUTHELIA_STORAGE_ENCRYPTION_KEY=$(rand 32)
AUTHELIA_JWT_SECRET=$(rand 32)
E2E_ADMIN_PASSWORD=$(rand 12)
E2E_ALICE_PASSWORD=$(rand 12)
E2E_BOB_PASSWORD=$(rand 12)
E2E_CAROL_PASSWORD=$(rand 12)
E2E_MINIO_USER=minioadmin
E2E_MINIO_PASSWORD=$(rand 16)
E2E_CTL_TOKEN=$(rand 24)
ENV
fi

FILES=(-f deploy/compose.yaml -f deploy/compose.e2e.yaml)
[ "$PUBLISH" = 1 ] && FILES+=(-f deploy/compose.e2e.publish.yaml)
PROFILES=(--profile authelia --profile runner)
[ "$SEARCH" = on ] && PROFILES+=(--profile search)
DC=(docker compose --project-directory deploy --env-file "$STATE/e2e.env" "${FILES[@]}" "${PROFILES[@]}")

collect() {
  mkdir -p "$OUT/logs"
  local svc
  for svc in $("${DC[@]}" config --services 2>/dev/null); do
    "${DC[@]}" logs --no-color --timestamps "$svc" > "$OUT/logs/$svc.log" 2>&1 || true
  done
  "${DC[@]}" ps -a > "$OUT/logs/_ps.txt" 2>&1 || true
}
teardown() {
  if [ "$KEEP" = 1 ]; then echo "e2e: stack left running (project $COMPOSE_PROJECT_NAME); secrets in e2e/.state/e2e.env"; return; fi
  "${DC[@]}" down -v --remove-orphans >/dev/null 2>&1
  if [ "$RMI" = 1 ]; then
    docker images --format '{{.Repository}}:{{.Tag}}' | grep -E '^sbe2e/' | xargs -r docker rmi >/dev/null 2>&1
  fi
  rm -f "$STATE/e2e.env"
}
trap teardown EXIT

rm -rf "$OUT/logs" "$OUT/results" "$OUT/report"
echo "== e2e: building images (one at a time)"
if [ "$BUILD" = 1 ]; then
  SVCS=(api web gateway vpn qbittorrent tracker seeder net-echo-direct front ctl playwright)
  [ "$SEARCH" = on ] && SVCS+=(indexer)
  for svc in "${SVCS[@]}"; do
    echo "-- build $svc"
    "${DC[@]}" build "$svc" || { echo "e2e: build of $svc failed" >&2; exit 2; }
  done
fi

echo "== e2e: starting the stack (layout: $LAYOUT, search: $SEARCH)"
UP=(front gateway authelia api worker vpn qbittorrent seeder minio net-echo-direct net-echo-behind wg1 wg2)
[ "$SEARCH" = on ] && UP+=(jackett indexer)
if ! "${DC[@]}" up -d --no-build --wait --wait-timeout 300 "${UP[@]}"; then
  echo "e2e: the stack did not become healthy" >&2
  collect; exit 3
fi
"${DC[@]}" ps

status=0
if [ "$TESTS" = 1 ]; then
  echo "== e2e: running Playwright"
  "${DC[@]}" run --rm --no-deps playwright npx playwright test "${PW_ARGS[@]}"
  status=$?
fi
collect
[ "$status" = 0 ] || echo "e2e: FAILED (exit $status); traces, screenshots and logs are in e2e/.out" >&2
exit $status
